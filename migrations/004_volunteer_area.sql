-- Volunteer area: door-to-door visits, pledges of support, and coordinator roles.
-- client_id is unique so a visit or pledge saved offline can be sent again without duplicating it.

CREATE TABLE IF NOT EXISTS visits (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id     BIGINT NOT NULL REFERENCES members (id) ON DELETE CASCADE,
  client_id     TEXT NOT NULL UNIQUE,
  visit_date    TEXT NOT NULL,
  households    INTEGER NOT NULL DEFAULT 0,
  people        INTEGER NOT NULL DEFAULT 0,
  area          TEXT NOT NULL DEFAULT '',
  notes         TEXT NOT NULL DEFAULT '',
  state         TEXT NOT NULL DEFAULT '',
  lga           TEXT NOT NULL DEFAULT '',
  ward          TEXT NOT NULL DEFAULT '',
  created_at    BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS visits_member_idx ON visits (member_id);
CREATE INDEX IF NOT EXISTS visits_state_created_idx ON visits (state, created_at);

CREATE TABLE IF NOT EXISTS pledges (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id     BIGINT NOT NULL REFERENCES members (id) ON DELETE CASCADE,
  client_id     TEXT NOT NULL UNIQUE,
  full_name     TEXT NOT NULL,
  phone         TEXT NOT NULL DEFAULT '',
  polling_unit  TEXT NOT NULL DEFAULT '',
  note          TEXT NOT NULL DEFAULT '',
  consent_at    BIGINT NOT NULL,
  state         TEXT NOT NULL DEFAULT '',
  lga           TEXT NOT NULL DEFAULT '',
  ward          TEXT NOT NULL DEFAULT '',
  created_at    BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS pledges_member_idx ON pledges (member_id);
CREATE INDEX IF NOT EXISTS pledges_state_created_idx ON pledges (state, created_at);

CREATE TABLE IF NOT EXISTS roles (
  member_id     BIGINT PRIMARY KEY REFERENCES members (id) ON DELETE CASCADE,
  role          TEXT NOT NULL CHECK (role IN ('state', 'national')),
  state         TEXT NOT NULL DEFAULT '',
  assigned_by   BIGINT,
  assigned_at   BIGINT NOT NULL
);
